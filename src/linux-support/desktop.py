"""Desktop integration for the OVLS nxm:// handler.

The module owns exactly three user-level artifacts:

  * ``$XDG_DATA_HOME/ovls/ovls-nxm`` — small wrapper around ``ovls.py nxm``;
  * ``$XDG_DATA_HOME/applications/ovls-nxm.desktop`` — protocol handler entry;
  * ``$XDG_DATA_HOME/ovls/nxm-previous-default`` — previous handler name, so
    uninstall can restore it when it still exists.

Registration uses ``xdg-mime default``. If no previous handler existed, uninstall
removes only our entry from the user's ``mimeapps.list`` and leaves everything
else intact.
"""

import os
import shlex
import shutil
import subprocess
import tempfile
from datetime import datetime, timezone
from pathlib import Path

import layout

HANDLER_ID = "ovls-nxm.desktop"
HANDLER_NAME = "ovls-nxm"
SCHEME = "x-scheme-handler/nxm"
STATE_FILE = "nxm-previous-default"
BACKUP_SUFFIX = "ovls-backup"


def data_home():
    return Path(os.environ.get("XDG_DATA_HOME") or Path.home() / ".local" / "share")


def config_home():
    return Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config")


def state_home():
    return Path(os.environ.get("XDG_STATE_HOME") or Path.home() / ".local" / "state")


def _applications_dir(explicit=None):
    if explicit:
        return Path(explicit).expanduser().resolve()
    return data_home() / "applications"


def _install_dir():
    return data_home() / "ovls"


def _wrapper_path():
    return _install_dir() / HANDLER_NAME


def _desktop_path(applications_dir=None):
    return _applications_dir(applications_dir) / HANDLER_ID


def _state_path():
    return _install_dir() / STATE_FILE


def _desktop_file(desktop_id, applications_dir=None):
    candidates = [
        _applications_dir(applications_dir) / desktop_id,
        data_home() / "applications" / desktop_id,
        Path("/usr/local/share/applications") / desktop_id,
        Path("/usr/share/applications") / desktop_id,
    ]
    return next((path for path in candidates if path.is_file()), None)


def _desktop_exec(path):
    """Quote a path for a .desktop Exec line (not shell quoting)."""
    value = str(path)
    if any(character in value for character in ' \t"`$\\'):
        value = value.replace("\\", "\\\\").replace('"', '\\"')
        value = value.replace("`", "\\`").replace("$", "\\$")
        return f'"{value}"'
    return value


def _render_wrapper(ovls_py, prefix):
    ovls = Path(ovls_py).expanduser().resolve()
    target = Path(prefix).expanduser().resolve()
    return (
        "#!/bin/sh\n"
        "# Generated by the OVLS Linux Support installer; re-run install to update.\n"
        f"exec python3 {shlex.quote(str(ovls))} nxm "
        f"--prefix {shlex.quote(str(target))} --uri \"$1\"\n"
    )


def _render_desktop(wrapper):
    return "\n".join(
        [
            "[Desktop Entry]",
            "Type=Application",
            "Name=OVLS NXM Handler",
            "Comment=Open nxm:// links in the official Vortex via Linux Support",
            f"Exec={_desktop_exec(wrapper)} %u",
            "Icon=ovls",
            "Terminal=false",
            "NoDisplay=true",
            "MimeType=x-scheme-handler/nxm;",
            "Categories=Game;",
            "StartupWMClass=Vortex",
            "",
        ]
    )


def _write_text(path, text, mode=None):
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temp_path = tempfile.mkstemp(
        prefix=f".{path.name}-", suffix=".tmp", dir=str(path.parent)
    )
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(text)
        if mode is not None:
            os.chmod(temp_path, mode)
        os.replace(temp_path, path)
    finally:
        if os.path.exists(temp_path):
            os.unlink(temp_path)


def _read(path):
    try:
        return path.read_text(encoding="utf-8")
    except OSError:
        return None


def _run_xdg_mime(arguments, runner=None):
    if runner is not None:
        return runner(arguments)
    try:
        return subprocess.run(
            ["xdg-mime", *arguments], check=False, capture_output=True, text=True
        )
    except OSError:
        return None


def current_default(runner=None):
    completed = _run_xdg_mime(["query", "default", SCHEME], runner)
    if completed is None:
        return None
    output = (getattr(completed, "stdout", "") or "").strip()
    return output or None


def _set_default(desktop_id, runner=None):
    completed = _run_xdg_mime(["default", desktop_id, SCHEME], runner)
    return completed is not None and getattr(completed, "returncode", 1) == 0


def _update_desktop_database(directory):
    if not shutil.which("update-desktop-database"):
        return
    try:
        subprocess.run(
            ["update-desktop-database", str(directory)],
            check=False,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
    except OSError:
        pass


def _remove_default_entry():
    """Remove our handler from the user's mimeapps.list, keeping other entries."""
    config = config_home() / "mimeapps.list"
    text = _read(config)
    if text is None:
        return False

    sections = {}
    current = None
    order = []
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("[") and stripped.endswith("]"):
            current = stripped
            order.append(current)
            sections.setdefault(current, [])
            continue
        if current is not None:
            sections[current].append(line)

    changed = False
    for section in ("[Default Applications]", "[Added Associations]"):
        if section not in sections:
            continue
        rendered = []
        for line in sections[section]:
            if not line.strip().startswith(f"{SCHEME}="):
                rendered.append(line)
                continue
            values = [value.strip() for value in line.split("=", 1)[1].split(";")]
            values = [value for value in values if value and value != HANDLER_ID]
            if values:
                rendered.append(f"{SCHEME}=" + ";".join(values) + ";")
            changed = True
        sections[section] = rendered

    if not changed:
        return False

    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    backup = config.with_name(f"{config.name}.{BACKUP_SUFFIX}-{stamp}")
    shutil.copy2(config, backup)

    output = []
    for section in order:
        output.append(section)
        output.extend(sections[section])
    _write_text(config, "\n".join(output).rstrip("\n") + "\n")
    return True


def install_handler(
    prefix,
    project_root,
    dry_run=False,
    applications_dir=None,
    register=True,
    runner=None,
    ovls_py=None,
):
    wrapper = _wrapper_path()
    desktop = _desktop_path(applications_dir)
    state = _state_path()
    if ovls_py is None:
        ovls_py = Path(project_root) / layout.CODE_TREE / "ovls.py"
    wrapper_text = _render_wrapper(ovls_py, prefix)
    desktop_text = _render_desktop(wrapper)

    previous = current_default(runner) if register else None
    changed = (
        _read(wrapper) != wrapper_text
        or _read(desktop) != desktop_text
    )
    registration_needed = bool(register and previous != HANDLER_ID)

    result = {
        "status": "would_install" if dry_run else "installed",
        "handler_id": HANDLER_ID,
        "scheme": SCHEME,
        "wrapper": str(wrapper),
        "desktop": str(desktop),
        "previous": previous,
        "registered": previous == HANDLER_ID,
        "changed": changed,
    }
    if dry_run:
        result["status"] = "would_install" if changed or registration_needed else "unchanged"
        return result

    if register and not state.is_file():
        _write_text(state, (previous or "") + "\n")
    if changed:
        _write_text(wrapper, wrapper_text, 0o755)
        _write_text(desktop, desktop_text, 0o644)

    registered = previous == HANDLER_ID
    if register and not registered:
        registered = _set_default(HANDLER_ID, runner)
    if registered:
        _update_desktop_database(desktop.parent)

    result["registered"] = registered
    if not changed and not registration_needed:
        result["status"] = "unchanged"
    elif register and not registered:
        result["status"] = "attention_required"
    return result


def handler_state(applications_dir=None, register=True, runner=None):
    wrapper = _wrapper_path()
    desktop = _desktop_path(applications_dir)
    current = current_default(runner) if register else None
    present = wrapper.is_file() and desktop.is_file()
    registered = (not register) or current == HANDLER_ID
    if present and registered:
        status = "ok"
    elif present or registered:
        status = "incomplete"
    else:
        status = "missing"
    return {
        "status": status,
        "handler_id": HANDLER_ID,
        "scheme": SCHEME,
        "wrapper": str(wrapper),
        "desktop": str(desktop),
        "current_default": current,
        "registered": registered,
    }


def remove_handler(
    dry_run=False,
    applications_dir=None,
    register=True,
    runner=None,
):
    wrapper = _wrapper_path()
    desktop = _desktop_path(applications_dir)
    state = _state_path()
    previous = None
    state_text = _read(state)
    if state_text is not None:
        previous = state_text.strip() or None

    result = {
        "status": "would_remove" if dry_run else "removed",
        "handler_id": HANDLER_ID,
        "scheme": SCHEME,
        "wrapper": str(wrapper),
        "desktop": str(desktop),
        "restored": None,
    }
    if dry_run:
        return result

    current = current_default(runner) if register else None
    if register and current == HANDLER_ID:
        if previous and previous != HANDLER_ID and _desktop_file(previous, applications_dir):
            if _set_default(previous, runner):
                result["restored"] = previous
        if result["restored"] is None:
            _remove_default_entry()

    for path in (wrapper, desktop, state):
        if path.exists():
            path.unlink()
    try:
        _install_dir().rmdir()
    except OSError:
        pass
    _update_desktop_database(_applications_dir(applications_dir))
    return result
