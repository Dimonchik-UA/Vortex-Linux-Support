"""Desktop shortcuts for the installed OVLS copy.

The module owns exactly five user-level artifacts:

  * ``$XDG_DATA_HOME/ovls/bin/ovls-vortex`` and ``ovls-manager`` wrappers that
    execute the installed ``ovls/ovls.py`` (the manifest decides the path, so
    copies installed from this checkout keep working);
  * ``ovls-vortex.desktop`` in the applications menu **and** on the desktop;
  * ``ovls-manager.desktop`` in the applications menu only.

No code is copied here: the installed package in ``$XDG_DATA_HOME/ovls`` is the
only copy. Every generated file carries an ownership marker; installation never
overwrites a file without the marker and removal deletes only owned files.
"""

import os
import shlex
import shutil
import subprocess
import tempfile
from pathlib import Path

import desktop
import layout
import tempfiles

APP_DIR = Path("ovls")
BIN_DIR = APP_DIR / "bin"
SUPPORT_TREE = layout.CODE_TREE
MARKER = "X-OVLS-Managed=true"
OWNER_LINE = "# Generated by OVLS shortcuts install"

VORTEX_DESKTOP = "ovls-vortex.desktop"
MANAGER_DESKTOP = "ovls-manager.desktop"
VORTEX_WRAPPER = "ovls-vortex"
MANAGER_WRAPPER = "ovls-manager"

ICON_OVLS = "ovls"
ICON_MANAGER = "applications-system"
ICON_NAME = "ovls.png"
ICON_DIRNAME = "assets"
ICON_TARGET_DIR = Path("icons") / "hicolor" / "256x256" / "apps"


def app_dir():
    return desktop.data_home() / APP_DIR


def bin_dir():
    return desktop.data_home() / BIN_DIR


def ovls_py():
    """The entry point of the installed package (never the project checkout).

    The installed copy may keep its code in ``ovls/`` (standalone package) or
    in ``src/linux-support`` (installed from this checkout), so the
    manifest decides. The module layout is the fallback.
    """
    installed = app_dir()
    try:
        manifest = (installed / "MANIFEST.sha256").read_text(encoding="utf-8")
    except OSError:
        return installed / SUPPORT_TREE / "ovls.py"
    for line in manifest.splitlines():
        parts = line.split(None, 1)
        if len(parts) == 2:
            relative = parts[1].strip()
            if relative == "ovls.py" or relative.endswith("/ovls.py"):
                return installed / relative
    return installed / SUPPORT_TREE / "ovls.py"


def _icon_source():
    """The bundled Vortex icon inside the installed copy.

    The standalone package keeps it in ``ovls/assets/vortex.png``; a checkout
    install keeps it in ``src/linux-support/assets/vortex.png``.  The
    manifest decides when it exists; before the first install (no manifest yet)
    both layouts are tried, because ``layout.py`` is the only thing that knows
    which one is running.
    """
    installed = app_dir()
    try:
        manifest = (installed / "MANIFEST.sha256").read_text(encoding="utf-8")
    except OSError:
        manifest = ""
    for line in manifest.splitlines():
        parts = line.split(None, 1)
        if len(parts) == 2:
            relative = parts[1].strip()
            if relative.endswith("/" + ICON_DIRNAME + "/" + ICON_NAME) or relative == ICON_DIRNAME + "/" + ICON_NAME:
                return installed / relative
    for candidate in (
        installed / SUPPORT_TREE / ICON_DIRNAME / ICON_NAME,
        installed / "ovls" / ICON_DIRNAME / ICON_NAME,
    ):
        if candidate.is_file():
            return candidate
    return installed / SUPPORT_TREE / ICON_DIRNAME / ICON_NAME


def _icon_target():
    return desktop.data_home() / ICON_TARGET_DIR / ICON_NAME


def _icon_marker_path():
    return _icon_target().with_suffix(_icon_target().suffix + ".ovls-owned")


def _icon_owned(marker):
    """An OVLS icon has a regular marker file carrying our ownership line."""
    return marker.is_file() and not marker.is_symlink() and _has_marker(marker, MARKER)


def install_icon(dry_run=False):
    """Install the Vortex icon into the user's hicolor theme.

    A foreign ``ovls.png`` (placed there by another program or by hand) is
    never overwritten: the companion ``.ovls-owned`` marker decides.  Removal
    deletes both the icon and the marker, so the foreign file survives.
    """
    source = _icon_source()
    target = _icon_target()
    marker = _icon_marker_path()
    if not source.is_file():
        return {"status": "absent", "source": str(source)}
    if target.is_symlink() or (target.exists() and not _icon_owned(marker)):
        return {"status": "skipped", "reason": "foreign_icon", "path": str(target)}
    if dry_run:
        if not target.is_file():
            return {"status": "would_install", "path": str(target)}
        return {"status": "unchanged", "path": str(target)}
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, target)
    _write_text(marker, MARKER + "\n", 0o644)
    return {"status": "installed", "path": str(target)}


def remove_icon():
    """Remove the OVLS-owned icon and its marker; foreign icons stay."""
    target = _icon_target()
    marker = _icon_marker_path()
    owned = _icon_owned(marker)
    removed, skipped = [], []
    for path in (marker, target):
        if not path.exists() and not path.is_symlink():
            continue
        if path.is_symlink():
            skipped.append({"path": str(path), "reason": "symlink"})
            continue
        if not owned:
            skipped.append({"path": str(path), "reason": "not_owned"})
            continue
        try:
            path.unlink()
            removed.append(str(path))
        except OSError:
            skipped.append({"path": str(path), "reason": "unlink_failed"})
    return {"status": "ok", "removed": removed, "skipped": skipped}


def icon_status():
    target = _icon_target()
    marker = _icon_marker_path()
    source = _icon_source()
    if not source.is_file():
        state = "source_missing"
    elif not target.is_file():
        state = "missing"
    elif not _icon_owned(marker):
        state = "foreign"
    else:
        state = "ok"
    return {"status": state, "path": str(target), "source": str(source)}


def applications_dir(explicit=None):
    if explicit:
        return Path(explicit).expanduser()
    return desktop.data_home() / "applications"


def _xdg_user_dir(kind):
    tool = shutil.which("xdg-user-dir")
    if not tool:
        return None
    try:
        result = subprocess.run(
            [tool, kind], capture_output=True, text=True, timeout=5, check=False
        )
    except (OSError, subprocess.SubprocessError):
        return None
    if result.returncode != 0:
        return None
    value = result.stdout.strip()
    return Path(value) if value else None


def _parse_user_dirs(path):
    values = {}
    try:
        lines = Path(path).read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return values
    home = str(Path.home())
    for line in lines:
        line = line.strip()
        if not line.startswith("XDG_") or "=" not in line:
            continue
        key, _, raw = line.partition("=")
        raw = raw.strip().strip('"')
        values[key[len("XDG_"):].replace("_DIR", "")] = Path(raw.replace("$HOME", home))
    return values


def desktop_dir(explicit=None):
    """Resolve the user's desktop directory without extra dependencies."""
    if explicit:
        return Path(explicit).expanduser()
    env_value = os.environ.get("XDG_DESKTOP_DIR")
    if env_value:
        return Path(env_value).expanduser()
    home = Path.home()
    resolved = _xdg_user_dir("DESKTOP")
    if resolved is not None and Path(resolved) != home:
        return Path(resolved)
    configured = _parse_user_dirs(desktop.config_home() / "user-dirs.dirs").get("DESKTOP")
    if configured:
        return configured
    return home / "Desktop"


def _write_text(path, text, mode=0o644):
    path.parent.mkdir(parents=True, exist_ok=True)
    tempfiles.cleanup_orphaned_files(path.parent, f".{path.name}-")
    descriptor, temp_path = tempfile.mkstemp(
        prefix=f".{path.name}-{os.getpid()}-", suffix=".tmp", dir=str(path.parent)
    )
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(text)
        os.chmod(temp_path, mode)
        os.replace(temp_path, path)
    finally:
        if os.path.exists(temp_path):
            os.unlink(temp_path)


def _desktop_exec(path):
    return desktop._desktop_exec(path)


def _has_marker(path, marker):
    try:
        return marker in Path(path).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return False


def _render_wrapper(command):
    return (
        "#!/bin/sh\n"
        f"{OWNER_LINE}; re-run it to update.\n"
        f"exec python3 {shlex.quote(str(ovls_py()))} {command} \"$@\"\n"
    )


def _render_desktop(name, comment, target, icon, categories, extra=()):
    lines = [
        "[Desktop Entry]",
        "Type=Application",
        f"Name={name}",
        f"Comment={comment}",
        f"Exec={_desktop_exec(target)}",
        f"Icon={icon}",
        "Terminal=false",
        f"Categories={categories}",
        *extra,
        MARKER,
        "",
    ]
    return "\n".join(lines)


def _managed_paths(applications=None, desktop_path=None):
    """Yield ``(path, marker)`` for every file OVLS may create."""
    apps = applications_dir(applications)
    on_desktop = desktop_dir(desktop_path)
    wrappers = bin_dir()
    yield wrappers / VORTEX_WRAPPER, OWNER_LINE
    yield wrappers / MANAGER_WRAPPER, OWNER_LINE
    yield apps / VORTEX_DESKTOP, MARKER
    yield apps / MANAGER_DESKTOP, MARKER
    yield on_desktop / VORTEX_DESKTOP, MARKER


def _desired(applications=None, desktop_path=None):
    apps = applications_dir(applications)
    on_desktop = desktop_dir(desktop_path)
    vortex_entry = _render_desktop(
        "Vortex",
        "Official Vortex on Linux",
        bin_dir() / VORTEX_WRAPPER,
        ICON_OVLS,
        "Game;",
        ("StartupWMClass=steam_proton",),
    )
    manager_entry = _render_desktop(
        "OVLS Manager",
        "OVLS Manager (Official Vortex Linux Support)",
        bin_dir() / MANAGER_WRAPPER,
        ICON_MANAGER,
        "Utility;",
    )
    return [
        (bin_dir() / VORTEX_WRAPPER, _render_wrapper("launcher"), OWNER_LINE, 0o755),
        (bin_dir() / MANAGER_WRAPPER, _render_wrapper("manager"), OWNER_LINE, 0o755),
        (apps / VORTEX_DESKTOP, vortex_entry, MARKER, 0o755),
        (apps / MANAGER_DESKTOP, manager_entry, MARKER, 0o755),
        (on_desktop / VORTEX_DESKTOP, vortex_entry, MARKER, 0o755),
    ]


def install(dry_run=False, applications=None, desktop_path=None):
    """Create or refresh wrappers and shortcuts, never overwriting foreign files."""
    written, would_write, skipped = [], [], []
    desired = _desired(applications, desktop_path)
    for path, text, marker, mode in desired:
        if path.is_symlink() or (path.exists() and not _has_marker(path, marker)):
            skipped.append({"path": str(path), "reason": "not_owned_by_ovls"})
            continue
        if dry_run:
            if not path.is_file() or path.read_text(encoding="utf-8", errors="replace") != text:
                would_write.append(str(path))
            continue
        _write_text(path, text, mode)
        written.append(str(path))

    code_present = ovls_py().is_file()
    icon = install_icon(dry_run=dry_run)
    icon_status_ok = icon.get("status") in ("installed", "unchanged", "absent")
    status = "ok" if not skipped and (dry_run or code_present) and icon_status_ok else "attention_required"
    return {
        "status": status,
        "dry_run": dry_run,
        "installed_code": str(ovls_py()),
        "icon": icon,
        "written": written,
        "would_write": would_write,
        "skipped": skipped,
        "shortcuts": [str(path) for path, *_ in desired],
    }


def remove(applications=None, desktop_path=None):
    """Remove only OVLS-owned shortcuts; foreign files are reported, not deleted."""
    removed, skipped = [], []
    for path, marker in _managed_paths(applications, desktop_path):
        if not path.exists() and not path.is_symlink():
            continue
        if path.is_symlink() or not _has_marker(path, marker):
            skipped.append({"path": str(path), "reason": "not_owned_by_ovls"})
            continue
        try:
            path.unlink()
            removed.append(str(path))
        except OSError:
            skipped.append({"path": str(path), "reason": "unlink_failed"})
    try:
        bin_dir().rmdir()
    except OSError:
        pass
    icon = remove_icon()
    return {
        "status": "ok",
        "removed": removed,
        "skipped": skipped,
        "icon": icon,
    }


def status(applications=None, desktop_path=None):
    """Report whether every owned artifact is present and still owned."""
    apps = applications_dir(applications)
    on_desktop = desktop_dir(desktop_path)
    expected = {
        "shortcut_vortex_menu": (apps / VORTEX_DESKTOP, MARKER),
        "shortcut_manager_menu": (apps / MANAGER_DESKTOP, MARKER),
        "shortcut_vortex_desktop": (on_desktop / VORTEX_DESKTOP, MARKER),
        "wrapper_vortex": (bin_dir() / VORTEX_WRAPPER, OWNER_LINE),
        "wrapper_manager": (bin_dir() / MANAGER_WRAPPER, OWNER_LINE),
        "installed_code": (ovls_py(), None),
    }
    files = {}
    for key, (path, marker) in expected.items():
        if not path.is_file():
            state = "missing"
        elif marker and not _has_marker(path, marker):
            state = "not_owned"
        else:
            state = "ok"
        files[key] = {"path": str(path), "status": state}
    files["icon_vortex"] = icon_status()
    ok = all(item["status"] == "ok" for item in files.values())
    return {
        "status": "ok" if ok else "attention_required",
        "desktop_dir": str(on_desktop),
        "applications_dir": str(apps),
        "installed_code": str(ovls_py()),
        "files": files,
    }
