#!/usr/bin/env python3
"""Assemble the standalone OVLS installer folder.

The project tree is the source of the installer, but it cannot be shipped as
is: it also contains research, tests, reports and the graph.  This tool copies
exactly the files the installer itself installs (``package._iter_sources``)
plus the ``OVLS Installer.desktop`` launcher into one folder that can be moved
anywhere — to ``~/Downloads``, to a USB stick, to another machine — and run
without the working project directory.

The package layout is the readable one, not the project one::

  OVLS Installer/
  ├── install.sh
  ├── OVLS Installer.desktop
  ├── README.md
  └── ovls/
      ├── *.py
      └── extension/{index.js,info.json}

``layout.py`` detects which layout is running, so both trees install the same
way.

Usage
-----
  scripts/build_package.py                       # -> dist/OVLS Installer
  scripts/build_package.py --out ~/Desktop/OVLS  # custom destination

The destination is a build artifact and is rewritten on every run.  To make
that safe, a non-empty destination is refused unless it was produced by this
tool earlier (``.ovls-build`` marker).
"""

import argparse
import hashlib
import json
import shutil
import sys
import tarfile
from datetime import datetime
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT / "src" / "linux-support"))

import layout  # noqa: E402
import package  # noqa: E402

DESKTOP_NAME = "OVLS Installer.desktop"
DEFAULT_OUT = PROJECT / "dist" / "OVLS Installer"
MARKER = ".ovls-build"


def _sources():
    """Return (path inside the package, source path) pairs.

    Sources are taken from the project tree, but the package layout is the
    readable one: code goes to ``ovls/`` and the Vortex Extension to
    ``ovls/extension/``.
    """
    pairs = []
    for relative, source in package._iter_sources(PROJECT):
        relative = Path(relative)
        try:
            rel_under = relative.relative_to(package.SUPPORT_TREE)
            target = layout.PACKAGE_CODE_TREE / rel_under
        except ValueError:
            if relative.parent == package.EXTENSION_TREE:
                target = layout.PACKAGE_EXTENSION_TREE / relative.name
            else:
                target = relative
        pairs.append((target, source))
    desktop = PROJECT / "installer" / DESKTOP_NAME
    if not desktop.is_file():
        raise SystemExit(f"ERROR: {DESKTOP_NAME} not found in {PROJECT / 'installer'}")
    pairs.append((Path(DESKTOP_NAME), desktop))
    return sorted(pairs)


def _prepare(out):
    if out.exists():
        if not out.is_dir():
            raise SystemExit(f"ERROR: {out} exists and is not a directory")
        if any(out.iterdir()) and not (out / MARKER).is_file():
            raise SystemExit(
                f"ERROR: {out} is not empty and was not built by this tool.\n"
                "Remove it manually or choose another --out."
            )
        shutil.rmtree(out)
    out.mkdir(parents=True)


def build(out=DEFAULT_OUT):
    out = Path(out).expanduser().resolve()
    sources = _sources()
    if not sources:
        raise SystemExit("ERROR: nothing to copy")
    _prepare(out)

    for relative, source in sources:
        target = out / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)

    entry = out / package.ENTRY_SCRIPT
    entry.chmod(entry.stat().st_mode | 0o111)
    desktop = out / DESKTOP_NAME
    desktop.chmod(desktop.stat().st_mode | 0o111)
    (out / MARKER).write_text(
        "Generated by Tools/build_package.py from "
        f"{PROJECT} at {datetime.now().isoformat(timespec='seconds')}.\n"
        "Do not edit: rerun the tool after changing the sources.\n",
        encoding="utf-8",
    )
    return out, len(sources)


def check(out):
    """Verify the built folder is complete and relocatable."""
    out = Path(out)
    problems = []
    for relative, _source in _sources():
        if not (out / relative).is_file():
            problems.append(f"missing: {relative}")
    entry = out / package.ENTRY_SCRIPT
    if entry.is_file() and not entry.stat().st_mode & 0o111:
        problems.append(f"not executable: {package.ENTRY_SCRIPT}")
    for relative, _source in _sources():
        path = out / relative
        if path.suffix not in (".py", ".sh", ".js"):
            continue
        if str(PROJECT) in path.read_text(encoding="utf-8"):
            problems.append(f"absolute project path: {relative}")
    return problems


def _sha256_file(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def write_archive(out, archive_path, checksum_path):
    """Write distributable archive and SHA256SUMS, excluding the build marker.

    The marker remains in the local build directory to protect it from accidental
    overwrite, but must not be shipped in the release archive.
    """
    out = Path(out)
    archive_path = Path(archive_path)
    checksum_path = Path(checksum_path)
    archive_path.parent.mkdir(parents=True, exist_ok=True)

    def _filter(tarinfo):
        if Path(tarinfo.name).name == MARKER:
            return None
        return tarinfo

    with tarfile.open(archive_path, "w:gz") as tar:
        tar.add(out, arcname=out.name, filter=_filter)

    digest = _sha256_file(archive_path)
    checksum_path.write_text(f"{digest}  {archive_path.name}\n", encoding="utf-8")
    return digest


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--out",
        default=str(DEFAULT_OUT),
        help=f"destination folder (default: {DEFAULT_OUT})",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="only verify an existing build folder",
    )
    parser.add_argument(
        "--archive",
        action="store_true",
        help="after a successful build and check, create OVLS-Installer.tar.gz and SHA256SUMS next to the build folder",
    )
    args = parser.parse_args(argv)

    out = Path(args.out).expanduser().resolve()
    if not args.check:
        out, count = build(out)
        print(f"built: {out}")
        print(f"files: {count}")

    problems = check(out)
    if problems:
        print("PROBLEMS:", file=sys.stderr)
        for problem in problems:
            print(f"  {problem}", file=sys.stderr)
        return 1

    if not args.check and args.archive:
        archive_path = out.parent / "OVLS-Installer.tar.gz"
        checksum_path = out.parent / "SHA256SUMS"
        digest = write_archive(out, archive_path, checksum_path)
        print(f"archive: {archive_path}")
        print(f"sha256: {digest}")

    print("check: ok")
    return 0


if __name__ == "__main__":
    sys.exit(main())
