"""Tests for src/linux-support/shortcuts.py.

Every test builds a throw-away HOME/XDG tree and a stub installed OVLS copy.
No real desktop, applications menu or project file is touched.
"""

import os
import shutil
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parents[1]
sys.path.insert(0, str(PROJECT / "src" / "linux-support"))

import shortcuts  # noqa: E402


class ShortcutsTest(unittest.TestCase):
    def setUp(self):
        self.root = Path(tempfile.mkdtemp(prefix="ovls-shortcuts-", dir=str(HERE)))
        self.data = self.root / "data"
        self.config = self.root / "config"
        self.state = self.root / "state"
        self.home = self.root / "home"
        self.desktop = self.root / "Desktop"
        self.apps = self.data / "applications"
        self.app = self.data / "ovls"
        self.code = self.app / "src" / "linux-support" / "ovls.py"
        self.code.parent.mkdir(parents=True)
        self.code.write_text("#!/usr/bin/env python3\n", encoding="utf-8")
        self.icon = self.app / "src" / "linux-support" / "assets" / "ovls.png"
        self.icon.parent.mkdir(parents=True)
        self.icon.write_bytes(b"\x89PNG\r\n\x1a\n")

        self.env = mock.patch.dict(
            os.environ,
            {
                "XDG_DATA_HOME": str(self.data),
                "XDG_CONFIG_HOME": str(self.config),
                "XDG_STATE_HOME": str(self.state),
                "XDG_DESKTOP_DIR": str(self.desktop),
                "HOME": str(self.home),
            },
        )
        self.env.start()
        self.addCleanup(self.env.stop)

    def tearDown(self):
        shutil.rmtree(self.root, ignore_errors=True)

    def _paths(self):
        return [
            self.apps / "ovls-vortex.desktop",
            self.apps / "ovls-manager.desktop",
            self.desktop / "ovls-vortex.desktop",
            self.app / "bin" / "ovls-vortex",
            self.app / "bin" / "ovls-manager",
        ]

    def _icon_paths(self):
        target = shortcuts._icon_target()
        return target, target.with_suffix(target.suffix + ".ovls-owned")

    def test_install_creates_shortcuts_that_use_the_installed_copy(self):
        result = shortcuts.install()

        self.assertEqual(result["status"], "ok", result)
        for path in self._paths():
            self.assertTrue(path.is_file(), str(path))
        self.assertFalse((self.desktop / "ovls-manager.desktop").exists())
        self.assertFalse((self.app / "MANIFEST.sha256").exists())
        self.assertFalse((self.app / "app").exists())

        for name in ("ovls-vortex", "ovls-manager"):
            text = (self.app / "bin" / name).read_text(encoding="utf-8")
            self.assertIn(str(self.code), text)
            self.assertNotIn(
                str(PROJECT / "src" / "linux-support" / "ovls.py"), text
            )
            self.assertIn("# Generated by OVLS shortcuts install", text)

        entry = (self.apps / "ovls-vortex.desktop").read_text(encoding="utf-8")
        self.assertIn("Terminal=false", entry)
        self.assertIn("X-OVLS-Managed=true", entry)
        manager = (self.apps / "ovls-manager.desktop").read_text(encoding="utf-8")
        self.assertIn("Name=OVLS Manager", manager)

    def test_install_is_idempotent(self):
        shortcuts.install()
        before = {path: path.read_bytes() for path in self._paths()}

        result = shortcuts.install()

        self.assertEqual(result["status"], "ok")
        self.assertEqual(before, {path: path.read_bytes() for path in self._paths()})

    def test_install_does_not_overwrite_foreign_files(self):
        self.apps.mkdir(parents=True)
        foreign = self.apps / "ovls-vortex.desktop"
        foreign.write_text("[Desktop Entry]\nName=My Vortex\n", encoding="utf-8")
        self.desktop.mkdir(parents=True)
        foreign_desktop = self.desktop / "ovls-vortex.desktop"
        foreign_desktop.write_text("mine\n", encoding="utf-8")

        result = shortcuts.install()

        self.assertEqual(result["status"], "attention_required")
        skipped = [item["path"] for item in result["skipped"]]
        self.assertIn(str(foreign), skipped)
        self.assertIn(str(foreign_desktop), skipped)
        self.assertEqual(foreign.read_text(encoding="utf-8"), "[Desktop Entry]\nName=My Vortex\n")
        self.assertEqual(foreign_desktop.read_text(encoding="utf-8"), "mine\n")
        self.assertTrue((self.apps / "ovls-manager.desktop").is_file())

    def test_remove_deletes_only_owned_files(self):
        shortcuts.install()
        self.apps.mkdir(parents=True, exist_ok=True)
        foreign = self.apps / "vortex.desktop"
        foreign.write_text("[Desktop Entry]\nName=User Vortex\n", encoding="utf-8")

        result = shortcuts.remove()

        self.assertEqual(result["status"], "ok")
        for path in self._paths():
            self.assertFalse(path.exists(), str(path))
        self.assertTrue(foreign.is_file())

    def test_remove_skips_foreign_file_at_our_path(self):
        self.apps.mkdir(parents=True)
        foreign = self.apps / "ovls-manager.desktop"
        foreign.write_text("mine\n", encoding="utf-8")

        result = shortcuts.remove()

        self.assertTrue(foreign.is_file())
        self.assertIn(str(foreign), [item["path"] for item in result["skipped"]])

    def test_dry_run_writes_nothing(self):
        result = shortcuts.install(dry_run=True)

        self.assertTrue(result["dry_run"])
        self.assertGreater(len(result["would_write"]), 0)
        for path in self._paths():
            self.assertFalse(path.exists(), str(path))

    def test_status_reports_missing_shortcut(self):
        shortcuts.install()
        self.assertEqual(shortcuts.status()["status"], "ok")

        (self.desktop / "ovls-vortex.desktop").unlink()
        state = shortcuts.status()

        self.assertEqual(state["status"], "attention_required")
        self.assertEqual(state["files"]["shortcut_vortex_desktop"]["status"], "missing")

    def test_status_reports_foreign_file_as_not_owned(self):
        shortcuts.install()
        (self.apps / "ovls-manager.desktop").write_text("mine\n", encoding="utf-8")

        state = shortcuts.status()

        self.assertEqual(
            state["files"]["shortcut_manager_menu"]["status"], "not_owned"
        )

    def test_remove_icon_deletes_owned_icon_and_marker(self):
        self.assertEqual(shortcuts.install()["icon"]["status"], "installed")
        target, marker = self._icon_paths()
        self.assertTrue(target.is_file())
        self.assertTrue(marker.is_file())

        result = shortcuts.remove_icon()

        self.assertEqual(result["status"], "ok")
        self.assertFalse(target.exists())
        self.assertFalse(marker.exists())

    def test_remove_icon_keeps_foreign_icon_without_marker(self):
        target, marker = self._icon_paths()
        target.parent.mkdir(parents=True)
        target.write_bytes(b"foreign")

        result = shortcuts.remove_icon()

        self.assertIn(str(target), [item["path"] for item in result["skipped"]])
        self.assertEqual(target.read_bytes(), b"foreign")
        self.assertFalse(marker.exists())
        self.assertEqual(shortcuts.icon_status()["status"], "foreign")

    def test_remove_icon_without_icon_is_noop(self):
        result = shortcuts.remove_icon()

        self.assertEqual(result["status"], "ok")
        self.assertEqual(result["removed"], [])
        self.assertEqual(result["skipped"], [])

    def test_remove_icon_keeps_icon_with_incorrect_marker(self):
        target, marker = self._icon_paths()
        target.parent.mkdir(parents=True)
        target.write_bytes(b"foreign")
        marker.write_text("not an OVLS marker\n", encoding="utf-8")

        result = shortcuts.remove_icon()

        self.assertIn(str(target), [item["path"] for item in result["skipped"]])
        self.assertIn(str(marker), [item["path"] for item in result["skipped"]])
        self.assertEqual(target.read_bytes(), b"foreign")
        self.assertEqual(marker.read_text(encoding="utf-8"), "not an OVLS marker\n")
        self.assertEqual(shortcuts.icon_status()["status"], "foreign")

    def test_install_does_not_take_over_icon_with_incorrect_marker(self):
        target, marker = self._icon_paths()
        target.parent.mkdir(parents=True)
        target.write_bytes(b"foreign")
        marker.write_text("not an OVLS marker\n", encoding="utf-8")

        result = shortcuts.install()

        self.assertEqual(result["icon"]["status"], "skipped")
        self.assertEqual(target.read_bytes(), b"foreign")

    def test_remove_icon_does_not_follow_icon_symlink(self):
        target, marker = self._icon_paths()
        target.parent.mkdir(parents=True)
        external = self.root / "external.png"
        external.write_bytes(b"keep")
        target.symlink_to(external)
        marker.write_text(shortcuts.MARKER + "\n", encoding="utf-8")

        result = shortcuts.remove_icon()

        self.assertTrue(target.is_symlink())
        self.assertEqual(external.read_bytes(), b"keep")
        self.assertFalse(marker.exists())
        self.assertIn(
            str(target),
            [item["path"] for item in result["skipped"] if item["reason"] == "symlink"],
        )


if __name__ == "__main__":
    unittest.main(verbosity=2)
